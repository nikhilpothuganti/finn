type S = [org: string, role: string, from: number, to: number | null];
type Ed = [school: string, degree: string, year: number];

const stint = ([org, role, from, to]: S): Stint => ({ org, role, from, to, symbol: ORG_SYMBOL[org] });

function person(
  id: string,
  name: string,
  headline: string,
  city: string,
  career: S[],
  education: Ed[],
  expertise: string[],
  relationship?: Person["relationship"],
): Person {
  return {
    id,
    name,
    headline,
    city,
    career: career.map(stint),
    education: education.map(([school, degree, year]) => ({ school, degree, year })),
    expertise,
    relationship,
    source: "synthetic",
  };
}

